#!/bin/sh
# 把"要点给外部模型"的几份文档拼成一个文件 —— 省得对方那边漏收某一份。
#
# 为什么是脚本而不是手拼：源文件（防御模式 / 演化史 / 审计报告 / CLAUDE.md）会一直改，
# 手拼出来的那份必然过期，而且**过期的拼装文件看起来和新鲜的一模一样**。
#
# 跑法： cd ~/projects/singularity && sh docs/生成外派包.sh
#
# ⚠️ 改这个脚本时注意：头部那段「本包包含什么」的表格是**手写的**，
#    增减源文件时要一起改，否则表格会跟实际内容对不上。

set -e
cd "$(dirname "$0")/.."          # 仓库根

OUT="docs/外派包-静默失败治理-20260912.md"
MATERIAL="docs/静默失败治理-外派材料.md"
# 后四份是材料 §六 点名的"可以补充给它的资料"
PARTS="docs/防御模式.md docs/演化史.md docs/审计报告-20260911.md CLAUDE.md"

for f in "$MATERIAL" $PARTS; do
  [ -f "$f" ] || { echo "缺文件: $f" >&2; exit 1; }
done

{
  printf '%s\n' \
    '# 外派包 —— 静默失败治理（拼接文件）' \
    '' \
    '> ⚠️ **本文件是拼装的**，不是手写的。源文件改了要重新生成（命令见文末）。' \
    '> 单独看请改 `docs/静默失败治理-外派材料.md`。' \
    '' \
    '**给谁看**：外部模型（设计题，不是补丁题）。**整份贴/上传这一个文件就够**，不用再找别的。' \
    '' \
    '---' \
    '' \
    '## 本包包含什么（按阅读顺序）' \
    '' \
    '| # | 内容 | 为什么在里面 |' \
    '|---|---|---|' \
    '| 一 | **静默失败治理 —— 外派材料** | **正题**。12 个已证案例 + 方法学 + 我们要你答的 4 个问题 |' \
    '| 二 | **防御模式（62 条）** | **必读**。症状→根因→规则的沉淀，材料里多次引用 |' \
    '| 三 | **演化史** | 历轮同类教训，材料让它自己说"静默失败是本仓库主要 bug 模式"就出自这里 |' \
    '| 四 | **审计报告（09-11 那轮）** | 上一轮全量审计，看得到"修过什么、当时怎么判断的" |' \
    '| 五 | **CLAUDE.md** | 模块地图 + 验证命令，回答问题时定位用 |' \
    '' \
    '**建议的读法**：先读第一部分（它是问题本身），需要细节时再翻二~五。' \
    '**不要**把第二部分当成"要修 62 条"——那是资料库，不是任务清单。' \
    '' \
    '---' \
    '' \
    '# 一、静默失败治理 —— 外派材料' \
    ''
  cat "$MATERIAL"
  printf '\n\n---\n\n# 二、防御模式（62 条）\n\n';      cat docs/防御模式.md
  printf '\n\n---\n\n# 三、演化史\n\n';                 cat docs/演化史.md
  printf '\n\n---\n\n# 四、审计报告（2026-09-11）\n\n';  cat docs/审计报告-20260911.md
  printf '\n\n---\n\n# 五、CLAUDE.md\n\n';              cat CLAUDE.md
  printf '%s\n' \
    '' \
    '---' \
    '' \
    '## 重新生成' \
    '' \
    '```sh' \
    'cd ~/projects/singularity && sh docs/生成外派包.sh' \
    '```' \
    '' \
    "源文件：\`$MATERIAL\` + 上面那四份。" \
    '⚠️ 防御模式/演化史/审计报告一直在改 —— **发之前重跑一次**，别用旧的。'
} > "$OUT"

echo "生成: $OUT"
wc -l < "$OUT" | tr -d ' ' | sed 's/^/行数 /'
wc -c < "$OUT" | tr -d ' ' | sed 's/^/字节 /'
# 自检：五节都得在，缺一节就是拼错了
for h in '# 一、静默失败治理' '# 二、防御模式' '# 三、演化史' '# 四、审计报告' '# 五、CLAUDE.md'; do
  grep -qF "$h" "$OUT" || { echo "⛔ 缺章节: $h" >&2; exit 1; }
done
echo "✅ 五节齐全"
