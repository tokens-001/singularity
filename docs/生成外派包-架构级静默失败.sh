#!/bin/sh
# 拼"架构级静默失败（设计题）"那份外派包。
#
# 为什么是脚本不是手拼：附录里的 `防御模式.md` 一直在改，手拼的必然过期，
# 而**过期的拼装文件看起来和新鲜的一模一样**（同 `生成外派包.sh` 的理由）。
#
# 跑法： cd ~/projects/singularity && sh docs/生成外派包-架构级静默失败.sh
#
# ⚠️ 头部那张「本包包含什么」的表是**手写的** —— 增减源文件时要一起改。

set -e
cd "$(dirname "$0")/.."          # 仓库根

OUT="docs/外派包-架构级静默失败-20260913.md"
MATERIAL="docs/外派材料-架构级静默失败-20260913.md"
PARTS="docs/防御模式.md"

for f in "$MATERIAL" $PARTS; do
  [ -f "$f" ] || { echo "缺文件: $f" >&2; exit 1; }
done

{
  printf '%s\n' \
    '# 外派包 —— 架构级静默失败（设计题）' \
    '' \
    '> ⚠️ **本文件是拼装的**，不是手写的。源文件改了要重新生成（命令见文末）。' \
    '> 单独看请改 `docs/外派材料-架构级静默失败-20260913.md`。' \
    '' \
    '**给谁看**：外部模型。**整份贴/上传这一个文件就够**，不需要访问代码库。' \
    '' \
    '**这是一道设计题，不是补丁题**：问的是"该不该动架构、我们列的方案可行性如何、顺序怎么排"。' \
    '' \
    '---' \
    '' \
    '## 本包包含什么（按阅读顺序）' \
    '' \
    '| # | 内容 | 为什么在里面 |' \
    '|---|---|---|' \
    '| 一 | **架构级静默失败 —— 外派材料** | **正题**。系统形状 + 实测数据 + 我们列的 7 条方案与可行性判断 + **已知错过的方向** + 要你答的 6 个问题 |' \
    '| 二 | **防御模式（66 条）** | **证据库**。第一节里"30% 属于这个形状"就是从这份数出来的；想核对我们的说法就翻它 |' \
    '' \
    '⚠️ **第二节不是任务清单** —— 那是**事故记录库**（症状→根因→规则），已经修完的、还在的都有。' \
    '不要把它当成"要修 66 条"。' \
    '' \
    '⚠️ **第一节的第六小节「我们已知错过的方向」最重要** —— 上一轮外派就是因为材料里带了假前提，' \
    '给出的方案**位置全猜错**。请先读那一节。' \
    '' \
    '---' \
    '' \
    '# 一、架构级静默失败 —— 外派材料' \
    ''
  cat "$MATERIAL"
  printf '\n\n---\n\n# 二、防御模式（66 条，证据库）\n\n'; cat docs/防御模式.md
  printf '%s\n' \
    '' \
    '---' \
    '' \
    '## 重新生成' \
    '' \
    '```sh' \
    'cd ~/projects/singularity && sh docs/生成外派包-架构级静默失败.sh' \
    '```' \
    '' \
    "源文件：\`$MATERIAL\` + \`docs/防御模式.md\`。" \
    '⚠️ 防御模式一直在改 —— **发之前重跑一次**，别用旧的。'
} > "$OUT"

# 打**绝对路径**（不是相对的）：这个脚本 cd 到仓库根再干活，调用方可能不在那儿
echo "生成: $OUT"
echo "绝对路径: $(cd "$(dirname "$OUT")" && pwd)/$(basename "$OUT")"
wc -l < "$OUT" | tr -d ' ' | sed 's/^/行数 /'
wc -c < "$OUT" | tr -d ' ' | sed 's/^/字节 /'
# 自检：两节都得在 + 六个问题都得在，缺一个就是拼错/材料被改残了
for h in '# 一、架构级静默失败' '# 二、防御模式'; do
  grep -qF "$h" "$OUT" || { echo "⛔ 缺章节: $h" >&2; exit 1; }
done
for q in '如果只能做一件' '最大的误判可能是什么' '有没有第四条路' '默认怀疑' '直接批评它'; do
  grep -qF "$q" "$OUT" || { echo "⛔ 缺问题: $q" >&2; exit 1; }
done
# 源码位置那一节：至少要能看到几个**真的文件路径**
for s in 'src/singularity/web/app.py' 'orchestrator.py:106-116' 'witness.py:52'; do
  grep -qF "$s" "$OUT" || { echo "⛔ 源码位置那节缺: $s" >&2; exit 1; }
done
# 「要方案」那半边：不能只剩判断题
grep -qF '改哪里' "$OUT" || { echo "⛔ 没要求对方给方案（缺「改哪里」）" >&2; exit 1; }
grep -qF '可能引入什么新的静默失败' "$OUT" || { echo "⛔ 没要求自查新引入的静默" >&2; exit 1; }
echo "✅ 两节齐全 + 五个关键问题 + 源码位置 + 要方案那半边，都在"
