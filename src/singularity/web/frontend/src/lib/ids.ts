/**
 * ids.ts — id 显示的唯一出口。
 *
 * 存在的理由：后端的任务号 / 项目号是**毫秒时间戳**，而各处一直写 `slice(0, 8)`
 * 截**前** 8 位 —— 那正好是**每 100 秒才进一位**的一段 ⇒ 同一批任务（规划器
 * 一次拆出来的）在任务列表、活动流里**全长一个样**。
 * 2026-09-15 真机现场：越界告警打出来是「17894825 改了本属 17894825 的文件
 * fizzbuzz.py」，读起来像"自己改了自己" —— 等于**没有这条信息**（而它长得像有）。
 *
 * 要有区分度得取**后** 8 位（随毫秒变）。后端同一条规矩见 `scheduler/tracker.short_id`。
 *
 * 别在这里做"友好名"（拿任务标题当显示名之类）—— 那是另一个问题；这里只管截短 id。
 */

/** 短 id —— 取**后** 8 位。短于 8 位的原样返回。 */
export function shortId(id: string | number | null | undefined): string {
  const s = String(id ?? '')
  return s.length > 8 ? s.slice(-8) : s
}
